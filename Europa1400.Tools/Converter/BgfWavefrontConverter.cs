using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Europa1400.Tools.Decoder.Txs;
using Europa1400.Tools.Extensions;
using Europa1400.Tools.Structs.Bgf;

namespace Europa1400.Tools.Converter
{
    internal class BgfWavefrontConverter
    {
        internal required string TargetDirectory { get; init; }

        internal void Convert(BgfStruct bgf, TxsStruct? txs, Dictionary<string, string> extractedTextures, string objectName)
        {
            var objSb = new StringBuilder();
            var mtlSb = new StringBuilder();
            var mtlFileName = $"{objectName}.mtl";

            objSb.AppendLine($"# Wavefront OBJ - {objectName}");
            objSb.AppendLine($"# Generated by Europa1400.Tools");
            objSb.AppendLine($"mtllib {mtlFileName}");
            objSb.AppendLine($"o {objectName}");
            objSb.AppendLine();

            var reorderedTextures = GetReorderedTextures(bgf);
            var facesByTexture = new Dictionary<int, List<(int va, int vb, int vc, (float u, float v) t1, (float u, float v) t2, (float u, float v) t3)>>();
            var allVertices = new List<(float x, float y, float z)>();
            var allNormals = new List<(float x, float y, float z)>();
            var vertexMap = new Dictionary<int, int>();

            for (var i = 0; i < bgf.MappingObject.VertexMappings.Length; i++)
            {
                var vm = bgf.MappingObject.VertexMappings[i];
                var idx = allVertices.Count;
                vertexMap[i] = idx;
                allVertices.Add((vm.Vertex1.X, vm.Vertex1.Y, -vm.Vertex1.Z));
                allNormals.Add((vm.Vertex2.X, vm.Vertex2.Y, -vm.Vertex2.Z));
            }

            var allTexCoords = new List<(float u, float v)>();
            var texCoordMap = new Dictionary<(int faceIndex, int vertIndex), int>();

            for (var ti = 0; ti < reorderedTextures.Count; ti++)
            {
                var faces = bgf.MappingObject.PolygonMappings
                    .Where(f => f.TextureIndex == ti)
                    .ToArray();

                if (faces.Length == 0) continue;

                var faceList = new List<(int va, int vb, int vc, (float u, float v) t1, (float u, float v) t2, (float u, float v) t3)>();

                foreach (var face in faces)
                {
                    var va = vertexMap[(int)face.Face.A];
                    var vb = vertexMap[(int)face.Face.B];
                    var vc = vertexMap[(int)face.Face.C];
                    var t1 = (face.TextureMapping.TextureCoordinates1.U, face.TextureMapping.TextureCoordinates1.V);
                    var t2 = (face.TextureMapping.TextureCoordinates2.U, face.TextureMapping.TextureCoordinates2.V);
                    var t3 = (face.TextureMapping.TextureCoordinates3.U, face.TextureMapping.TextureCoordinates3.V);

                    allTexCoords.Add(t1);
                    allTexCoords.Add(t2);
                    allTexCoords.Add(t3);

                    faceList.Add((va, vb, vc, t1, t2, t3));
                }

                facesByTexture[ti] = faceList;
            }

            foreach (var v in allVertices)
                objSb.AppendLine(string.Format(CultureInfo.InvariantCulture, "v {0:F6} {1:F6} {2:F6}", v.x, v.y, v.z));

            objSb.AppendLine();
            foreach (var vn in allNormals)
                objSb.AppendLine(string.Format(CultureInfo.InvariantCulture, "vn {0:F6} {1:F6} {2:F6}", vn.x, vn.y, vn.z));

            objSb.AppendLine();
            foreach (var vt in allTexCoords)
                objSb.AppendLine(string.Format(CultureInfo.InvariantCulture, "vt {0:F6} {1:F6}", vt.u, vt.v));

            objSb.AppendLine();

            mtlSb.AppendLine($"# Material file - {objectName}");
            foreach (var (texture, textureIndex) in reorderedTextures.Select((t, i) => (t, i)))
            {
                if (!facesByTexture.ContainsKey(textureIndex)) continue;

                var textureName = Sanitize(texture.Name);
                var materialName = string.IsNullOrEmpty(textureName) ? $"material_{textureIndex}" : textureName;
                var texturePath = GetTexturePath(texture.Name, extractedTextures, txs);

                mtlSb.AppendLine($"newmtl {materialName}");
                mtlSb.AppendLine("Ka 1.0 1.0 1.0");
                mtlSb.AppendLine("Kd 1.0 1.0 1.0");
                mtlSb.AppendLine("Ks 0.0 0.0 0.0");
                mtlSb.AppendLine("d 1.0");
                mtlSb.AppendLine("illum 1");
                if (texturePath != null)
                    mtlSb.AppendLine($"map_Kd {Path.GetFileName(texturePath)}");
                mtlSb.AppendLine();
            }

            var tcOffset = 1;
            foreach (var (texture, textureIndex) in reorderedTextures.Select((t, i) => (t, i)))
            {
                if (!facesByTexture.TryGetValue(textureIndex, out var faceList)) continue;

                var textureName = Sanitize(texture.Name);
                var materialName = string.IsNullOrEmpty(textureName) ? $"material_{textureIndex}" : textureName;

                objSb.AppendLine($"usemtl {materialName}");

                foreach (var (va, vb, vc, _, _, _) in faceList)
                {
                    objSb.AppendLine($"f {va + 1}/{tcOffset}/{va + 1} {vb + 1}/{tcOffset + 1}/{vb + 1} {vc + 1}/{tcOffset + 2}/{vc + 1}");
                    tcOffset += 3;
                }

                objSb.AppendLine();
            }

            var objDir = Path.Combine(TargetDirectory, objectName);
            Directory.CreateDirectory(objDir);

            File.WriteAllText(Path.Combine(objDir, $"{objectName}.obj"), objSb.ToString(), Encoding.ASCII);
            File.WriteAllText(Path.Combine(objDir, mtlFileName), mtlSb.ToString(), Encoding.ASCII);
        }

        private static List<BgfTextureStruct> GetReorderedTextures(BgfStruct bgf)
        {
            var textures = new List<BgfTextureStruct>();
            var missingTextures = new List<BgfTextureStruct>();

            var textureNames = bgf.Textures
                .Select(e => e.Name.NormalizeName());
            var footerNames = bgf.Footer.TextureNames
                .Select(e => e.Name)
                .Where(e => textureNames.Contains(e.NormalizeName()));
            var normalizedFooterNames = footerNames
                .Select(e => e.NormalizeName())
                .ToList();

            foreach (var texture in bgf.Textures)
            {
                var normalizedName = texture.Name.NormalizeName();
                if (!normalizedFooterNames.Contains(normalizedName))
                {
                    missingTextures.Add(texture);
                    continue;
                }

                textures.Add(texture);
            }

            textures
                .Sort((e, f) => normalizedFooterNames.IndexOf(e.Name.NormalizeName())
                    .CompareTo(normalizedFooterNames.IndexOf(f.Name.NormalizeName())));

            textures.AddRange(missingTextures);
            return textures;
        }

        private static string? GetTexturePath(string textureName, Dictionary<string, string> extractedTextures,
            TxsStruct? txs)
        {
            while (true)
            {
                foreach (var (extractedTextureName, extractedTexturePath) in extractedTextures)
                    if (extractedTextureName.NormalizeName() == textureName.NormalizeName())
                        return extractedTexturePath;

                if (txs is null) return null;
                textureName = txs.TextureNames[0];
                txs = null;
            }
        }

        private static string Sanitize(string name)
        {
            return Path.GetInvalidFileNameChars().Aggregate(name, (current, c) => current.Replace(c, '_'));
        }
    }
}
